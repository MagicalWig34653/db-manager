func TestReviewA_CSVHostileInputs(t *testing.T) {
	e := testEngine(t)
	c := sqliteConnection()
	execute(t, e, c, "CREATE TABLE rva_csv (id INTEGER, value TEXT)")
	base := core.ImportRequest{Connection: c, Format: "csv", Table: core.TableRef{Name: "rva_csv"}, CSV: core.CSVImportOptions{Columns: []string{"id", "value"}}}
	plan := func(r core.ImportRequest, file []byte) (core.ImportPlan, error) {
		return e.PlanImport(context.Background(), r, file)
	}
	bad := map[string][]byte{
		"nul":              []byte("1,a\x00b\n"),
		"invalid-utf8":     []byte("1,\xff\xfe\n"),
		"utf16-bom":        []byte("\xff\xfe1\x00,\x00a\x00\n\x00"),
		"unterminated":     []byte("1,\"abc\n2,def\n"),
		"quote-mid-field":  []byte("1,ab\"cd\n"),
		"text-after-quote": []byte("1,\"ab\"cd\n"),
		"huge-cell":        append([]byte("1,"), bytes.Repeat([]byte("x"), 1<<20+1)...),
	}
	for name, file := range bad {
		if p, err := plan(base, file); err == nil && p.ValidRows > 0 {
			t.Errorf("%s accepted: %+v", name, p)
		}
	}
	// 1024+1 columns, huge row (4 MiB sum), too many rows.
	wide := base
	wide.CSV.Columns = nil
	if _, err := plan(wide, []byte("1\n")); err == nil {
		t.Error("no columns accepted")
	}
	// Cell exactly at the limit is accepted, in a quoted field with newlines.
	ok := append([]byte("1,\""), bytes.Repeat([]byte("y\n"), (1<<20)/2)...)
	ok = append(ok, '"', '\n')
	if p, err := plan(base, ok); err != nil || p.ValidRows != 1 {
		t.Errorf("1 MiB cell rejected: %v", err)
	}
	// BOM handling, CR-only line endings, quoted newline, tab separator.
	b := base
	b.CSV.Header = true
	p, err := plan(b, []byte("\xef\xbb\xbfid,value\r1,\"a\r\nb\"\r2,c"))
	if err != nil || p.ValidRows != 2 {
		t.Errorf("bom/cr: %+v %v", p, err)
	}
	b.CSV.Separator = "\t"
	if p, err = plan(b, []byte("id\tvalue\n1\t\"x\ty\"\n")); err != nil || p.ValidRows != 1 {
		t.Errorf("tab: %+v %v", p, err)
	}
	// Separator/quote validation.
	for _, sep := range []string{"\n", "\\", "\"", "ab", "\x00"} {
		b := base
		b.CSV.Separator = sep
		if _, err := plan(b, []byte("1,a\n")); err == nil {
			t.Errorf("separator %q accepted", sep)
		}
	}
	// Row limit.
	many := bytes.Repeat([]byte("1,a\n"), 100001)
	if _, err := plan(base, many); err == nil {
		t.Error("100001 rows accepted")
	}
	// Injection payloads are bound values.
	payload := "1,\"x'); DROP TABLE rva_csv;--\"\n"
	p, err = plan(base, []byte(payload))
	if err != nil {
		t.Fatal(err)
	}
	if got, err := e.ExecuteImport(context.Background(), importConfirm(base, p), []byte(payload), nil); err != nil || got.Inserted != 1 {
		t.Fatalf("%+v %v", got, err)
	}
	if scalar(t, reviewSystem{"sqlite", c, e}, "SELECT value FROM rva_csv") != "x'); DROP TABLE rva_csv;--" {
		t.Fatal("payload not stored literally")
	}
}

