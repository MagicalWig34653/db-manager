type reviewSystem struct {
	name string
	c    core.Connection
	e    *Engine
}

func reviewSystems(t *testing.T) []reviewSystem {
	t.Helper()
	out := []reviewSystem{{"sqlite", sqliteConnection(), testEngine(t)}}
	for _, s := range []struct{ name, driver, env string }{{"mysql", "mysql", "DBM_TEST_MYSQL_PORT"}, {"maria", "mysql", "DBM_TEST_MARIA_PORT"}, {"postgres", "postgres", "DBM_TEST_POSTGRES_PORT"}} {
		raw := os.Getenv(s.env)
		if raw == "" {
			continue
		}
		port, err := strconv.Atoi(raw)
		if err != nil {
			t.Fatal(err)
		}
		e, err := New(t.TempDir(), nil, WithCAFile(os.Getenv("DBM_TEST_CA_FILE")))
		if err != nil {
			t.Fatal(err)
		}
		c := core.Connection{Driver: s.driver, Host: "localhost", Port: port, Database: "probe", Username: "root", Password: os.Getenv("DBM_TEST_PASSWORD"), TLSMode: "verify-full"}
		if s.driver == "postgres" {
			c.Username = "postgres"
		}
		out = append(out, reviewSystem{s.name, c, e})
	}
	return out
}
func eachReviewSystem(t *testing.T, f func(t *testing.T, s reviewSystem)) {
	for _, s := range reviewSystems(t) {
		s := s
		t.Run(s.name, func(t *testing.T) { f(t, s) })
	}
}
func scalar(t *testing.T, s reviewSystem, q string) string {
	t.Helper()
	return execute(t, s.e, s.c, q).Results[0].Rows[0][0].Value
}
func autoPKDDL(s reviewSystem, table string) string {
	switch s.c.Driver {
	case "mysql":
		return "CREATE TABLE " + table + " (id INT AUTO_INCREMENT PRIMARY KEY, label VARCHAR(50)) ENGINE=InnoDB"
	case "postgres":
		return "CREATE TABLE " + table + " (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label VARCHAR(50))"
	}
	return "CREATE TABLE " + table + " (id INTEGER PRIMARY KEY, label VARCHAR(50))"
}
func dropIf(t *testing.T, s reviewSystem, names ...string) {
	for _, n := range names {
		_, _ = s.e.Query(context.Background(), core.QueryRequest{Connection: s.c, SQL: "DROP TABLE IF EXISTS " + n})
	}
}

// Replay: a confirmed CSV import request can be executed again and inserts the
// file a second time (no single-use plan, no idempotency key).
func TestReviewA_CSVImportReplayRefused(t *testing.T) {
	eachReviewSystem(t, func(t *testing.T, s reviewSystem) {
		dropIf(t, s, "rva_replay")
		execute(t, s.e, s.c, "CREATE TABLE rva_replay (id INTEGER, value VARCHAR(20))")
		defer dropIf(t, s, "rva_replay")
		r := core.ImportRequest{Connection: s.c, Format: "csv", Table: core.TableRef{Name: "rva_replay"}, CSV: core.CSVImportOptions{Columns: []string{"id", "value"}}}
		file := []byte("1,a\n2,b\n")
		p, err := s.e.PlanImport(context.Background(), r, file)
		if err != nil {
			t.Fatal(err)
		}
		c := importConfirm(r, p)
		if got, err := s.e.ExecuteImport(context.Background(), c, file, nil); err != nil || got.Outcome != "completed" {
			t.Fatalf("first run: %#v %v", got, err)
		}
		if _, err := s.e.ExecuteImport(context.Background(), c, file, nil); err == nil || !strings.Contains(err.Error(), "bereits ausgeführt") {
			t.Fatalf("replay must be refused as consumed plan, got %v", err)
		}
		if n := scalar(t, s, "SELECT COUNT(*) FROM rva_replay"); n != "2" {
			t.Fatalf("replayed confirmed import inserted %s rows instead of being rejected", n)
		}
	})
}

