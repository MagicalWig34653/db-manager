func TestReviewA_GzipBomb(t *testing.T) {
	engineIndependent(t)
	var buf bytes.Buffer
	z, _ := gzip.NewWriterLevel(&buf, gzip.BestCompression)
	chunk := make([]byte, 1<<20)
	for i := range chunk {
		chunk[i] = 'a'
	}
	for i := 0; i < 600; i++ { // 600 MiB expanded, a few hundred KiB compressed
		_, _ = z.Write(chunk)
	}
	_ = z.Close()
	t.Logf("compressed=%d bytes", buf.Len())
	e := testEngine(t)
	// Peak heap must stay near the 64 MiB bound, not follow the 600 MiB expansion.
	var peak atomic.Uint64
	stop := make(chan struct{})
	go func() {
		for {
			select {
			case <-stop:
				return
			default:
			}
			var m runtime.MemStats
			runtime.ReadMemStats(&m)
			if m.HeapAlloc > peak.Load() {
				peak.Store(m.HeapAlloc)
			}
			time.Sleep(time.Millisecond)
		}
	}()
	defer func() {
		close(stop)
		if peak.Load() > 400<<20 {
			t.Errorf("gzip bomb drove the heap to %d MiB", peak.Load()>>20)
		}
	}()
	for _, format := range []string{"sql", "csv"} {
		r := core.ImportRequest{Connection: sqliteConnection(), Format: format, Compression: "gzip", Table: core.TableRef{Name: "x"}, CSV: core.CSVImportOptions{Columns: []string{"a"}}, Confirm: &dbplan.Confirmation{Action: "import_" + format}}
		start := time.Now()
		_, err := e.ExecuteImport(context.Background(), r, buf.Bytes(), nil)
		if err == nil || !strings.Contains(err.Error(), "Bytegrenze") && !strings.Contains(err.Error(), "grenz") {
			t.Fatalf("%s bomb: %v", format, err)
		}
		if time.Since(start) > 10*time.Second {
			t.Fatalf("slow rejection %v", time.Since(start))
		}
	}
	// Truncated/corrupt gzip and a gzip stream declared as plain text.
	if _, err := e.ExecuteImport(context.Background(), core.ImportRequest{Connection: sqliteConnection(), Format: "sql", Compression: "gzip", Confirm: &dbplan.Confirmation{Action: "import_sql"}}, buf.Bytes()[:100], nil); err == nil {
		t.Fatal("truncated gzip accepted")
	}
	if _, err := e.ExecuteImport(context.Background(), core.ImportRequest{Connection: sqliteConnection(), Format: "sql", Confirm: &dbplan.Confirmation{Action: "import_sql"}}, buf.Bytes(), nil); err == nil {
		t.Fatal("gzip bytes accepted as plain SQL")
	}
}

